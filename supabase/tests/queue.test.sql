begin;
create extension if not exists pgtap with schema extensions;
select plan(12);
-- Isolate the fixture inside this rolled-back transaction even after real local intake.
update academy.production_jobs set available_at=now()+interval '1 day' where status='queued';
update academy.production_jobs set lease_expires_at=now()+interval '1 day' where status='running';
select ok(not has_function_privilege('authenticated','academy.renew_job(uuid,uuid)','execute'),'Readers cannot renew leases');
select ok(not has_function_privilege('anon','academy.enqueue_job(text,text,jsonb,uuid)','execute'),'Anonymous cannot enqueue');
create temporary table fixture_job as select academy.enqueue_job('normalize_source','test:sql:queue','{"identifier":"2401.12345"}') as id;
select is(academy.enqueue_job('normalize_source','test:sql:queue','{}'), (select id from fixture_job),'Idempotency returns same job');
create temporary table lease as select id,lease_token from academy.claim_job();
select is((select count(*) from lease),1::bigint,'One job claimed');
select is((select attempts from academy.production_jobs where id=(select id from fixture_job)),1,'Claim increments attempts');
select ok(not academy.finish_job((select id from lease),gen_random_uuid(),'{}'),'Wrong lease cannot finish');
select ok(academy.renew_job((select id from lease),(select lease_token from lease)),'Active lease renews');
select ok(academy.finish_job((select id from lease),(select lease_token from lease),'{"canonicalId":"arxiv:2401.12345"}'),'Worker finishes with exact lease');
select ok(not academy.finish_job((select id from lease),(select lease_token from lease),'{}'),'Completed lease cannot finish twice');
select is((select status from academy.production_jobs where id=(select id from fixture_job)),'succeeded','Job completed');
select is((select count(*) from academy.claim_job()),0::bigint,'Completed job is not claimed again');
select is((select public from storage.buckets where id='dobrov-academy-assets'),false,'Academy bucket is private');
select * from finish();
rollback;
